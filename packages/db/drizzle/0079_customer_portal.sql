-- Recomputes one ticket's `portal_contact_ids` after a CC or an identity changed.
CREATE FUNCTION public.helpdock_ticket_portal_refresh(p_ticket_id uuid)
RETURNS void
LANGUAGE sql
SET search_path = ''
SET app.all_departments = 'true'
AS $$
  UPDATE public.tickets AS t
  SET portal_contact_ids = fresh.ids
  FROM (
    SELECT public.helpdock_portal_contact_ids(x.id, x.contact_id, x.portal_eligible) AS ids
    FROM public.tickets AS x
    WHERE x.id = p_ticket_id
  ) AS fresh
  WHERE t.id = p_ticket_id AND t.portal_contact_ids IS DISTINCT FROM fresh.ids;
$$;--> statement-breakpoint

-- On the ticket itself, whichever code path writes it: the account follows the
-- requester, and the three portal facts follow the ticket's own state. A caller
-- cannot set any of them; whatever it passes is overwritten.
--
-- `portal_eligible` fails closed: a status the transaction cannot read, or no
-- status, is "not eligible".
CREATE FUNCTION public.helpdock_ticket_portal_scope()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
  NEW.account_id := (SELECT c.account_id FROM public.contacts c WHERE c.id = NEW.contact_id);
  NEW.portal_eligible := NEW.deleted_at IS NULL
    AND NEW.merged_into_id IS NULL
    AND coalesce(
      (SELECT NOT s.is_spam FROM public.ticket_statuses s WHERE s.id = NEW.status_id),
      false
    );
  NEW.portal_contact_ids :=
    public.helpdock_portal_contact_ids(NEW.id, NEW.contact_id, NEW.portal_eligible);

  RETURN NEW;
END;
$$;--> statement-breakpoint

CREATE TRIGGER tickets_portal_scope
BEFORE INSERT OR UPDATE OF contact_id, deleted_at, merged_into_id, status_id,
  account_id, portal_eligible, portal_contact_ids ON public.tickets
FOR EACH ROW
EXECUTE FUNCTION public.helpdock_ticket_portal_scope();--> statement-breakpoint

