-- A contact moved to another account (or out of one): its tickets follow, the
-- old account's members lose them and the new account's gain them, and the new
-- account is passed down to their messages and attachments in the same call.
CREATE FUNCTION public.helpdock_contact_portal_account()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
SET app.all_departments = 'true'
AS $$
BEGIN
  -- `tickets_portal_push` would otherwise run once per ticket, twice. The flag
  -- is local to the transaction and put back before returning.
  PERFORM pg_catalog.set_config('app.portal_bulk_push', 'on', true);

  UPDATE public.tickets
  SET account_id = NEW.account_id
  WHERE brand_id = NEW.brand_id
    AND contact_id = NEW.id
    AND account_id IS DISTINCT FROM NEW.account_id;

  UPDATE public.ticket_messages AS m
  SET portal_account_id = CASE WHEN t.portal_eligible AND NOT t.portal_private THEN t.account_id END
  FROM public.tickets AS t
  WHERE t.brand_id = NEW.brand_id
    AND t.contact_id = NEW.id
    AND m.ticket_id = t.id
    AND m.kind IN ('public', 'ai')
    AND m.portal_account_id IS DISTINCT FROM
        CASE WHEN t.portal_eligible AND NOT t.portal_private THEN t.account_id END;

  UPDATE public.attachments AS a
  SET portal_account_id = m.portal_account_id
  FROM public.ticket_messages AS m
  JOIN public.tickets AS t ON t.id = m.ticket_id
  WHERE t.brand_id = NEW.brand_id
    AND t.contact_id = NEW.id
    AND a.message_id = m.id
    AND a.portal_account_id IS DISTINCT FROM m.portal_account_id;

  PERFORM pg_catalog.set_config('app.portal_bulk_push', 'off', true);

  RETURN NULL;
END;
$$;--> statement-breakpoint

