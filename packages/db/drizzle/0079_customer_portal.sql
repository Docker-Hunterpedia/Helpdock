-- M21-01 (ADR 0060, DOMAIN-RULES §1.3). What the Drizzle schema cannot express:
-- the triggers that keep the customer portal's denormalised columns true, and the
-- backfill of rows that already exist.
--
-- The customer policy may not join (§1.3), so it reads columns that already sit
-- on the row it guards, exactly as the department policy reads `department_id`:
--
--   tickets.account_id          the requester's account now
--   tickets.portal_eligible     not deleted, not merged away, not Spam
--   tickets.portal_contact_ids  the requester, plus every CC whose address is a
--                               verified email identity of that CC's contact
--   ticket_messages / attachments .portal_contact_ids, .portal_account_id
--                               the ticket's, copied down; empty for a note
--
-- Every function is invoker-rights, like the department triggers: the statements
-- they issue are bound by row-level security. The ones that reach *other*
-- tickets (a CC added, an identity verified, a contact moved to another account)
-- carry `SET app.all_departments = 'true'` for the length of the call, the way
-- `helpdock_contact_ticket_count` does, because a department-scoped agent
-- changing a contact still has to update that contact's tickets in departments
-- they cannot read. `app.brand_ids` is untouched, so the brand policy still
-- applies.

-- The contacts on one ticket as far as the portal is concerned. Not eligible
-- means nobody. A CC counts only through a verified email identity of the
-- contact that is the CC (ADR 0060 §7), never by address alone.
CREATE FUNCTION public.helpdock_portal_contact_ids(
  p_ticket_id uuid,
  p_contact_id uuid,
  p_eligible boolean
)
RETURNS uuid[]
LANGUAGE sql
STABLE
SET search_path = ''
AS $$
  SELECT CASE
    WHEN p_eligible IS NOT TRUE THEN '{}'::uuid[]
    ELSE coalesce((
      SELECT pg_catalog.array_agg(DISTINCT member.contact_id)
      FROM (
        SELECT p_contact_id AS contact_id WHERE p_contact_id IS NOT NULL
        UNION
        SELECT tp.contact_id
        FROM public.ticket_participants tp
        JOIN public.contact_identities ci
          ON ci.contact_id = tp.contact_id
         AND ci.kind = 'email'
         AND ci.verified
         AND pg_catalog.lower(ci.value) = pg_catalog.lower(tp.address)
        -- Only a CC a staff action made: an agent adding it, or a staff-initiated merge.
        -- Mail (its authentication cannot be proved from the headers) and an import never count.
        WHERE tp.ticket_id = p_ticket_id AND tp.address IS NOT NULL
          AND tp.source::text IN ('agent', 'merge')
      ) AS member
    ), '{}'::uuid[])
  END;
$$;--> statement-breakpoint

