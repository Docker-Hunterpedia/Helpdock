-- attachment on one; an attachment not yet linked to a message carries nothing.
CREATE FUNCTION public.helpdock_ticket_portal_push()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
SET app.all_departments = 'true'
AS $$
DECLARE
  v_account uuid := CASE WHEN NEW.portal_eligible AND NOT NEW.portal_private THEN NEW.account_id END;
BEGIN
  -- A contact moved to another account pushes the whole set of its tickets down
  -- in one statement per table (`helpdock_contact_portal_account`), which is
  -- what makes a move of 50,000 tickets a matter of seconds and not minutes.
  IF pg_catalog.current_setting('app.portal_bulk_push', true) = 'on' THEN
    RETURN NULL;
  END IF;

  UPDATE public.ticket_messages AS m
  SET portal_contact_ids = NEW.portal_contact_ids,
      portal_account_id = v_account
  WHERE m.ticket_id = NEW.id
    AND m.kind IN ('public', 'ai')
    AND (m.portal_contact_ids IS DISTINCT FROM NEW.portal_contact_ids
         OR m.portal_account_id IS DISTINCT FROM v_account);

  UPDATE public.attachments AS a
  SET portal_contact_ids = m.portal_contact_ids,
      portal_account_id = m.portal_account_id
  FROM public.ticket_messages AS m
  WHERE a.ticket_id = NEW.id
    AND m.id = a.message_id
    AND (a.portal_contact_ids IS DISTINCT FROM m.portal_contact_ids
         OR a.portal_account_id IS DISTINCT FROM m.portal_account_id);

  RETURN NULL;
END;
$$;--> statement-breakpoint

-- No column list on purpose: `tickets_portal_scope` changes these columns in a
-- BEFORE trigger, and a column-specific AFTER trigger fires only for columns the
-- statement itself names. The WHEN clause is what keeps it cheap.
CREATE TRIGGER tickets_portal_push
AFTER UPDATE ON public.tickets
FOR EACH ROW
WHEN (
  OLD.account_id IS DISTINCT FROM NEW.account_id
  OR OLD.portal_private IS DISTINCT FROM NEW.portal_private
  OR OLD.portal_eligible IS DISTINCT FROM NEW.portal_eligible
  OR OLD.portal_contact_ids IS DISTINCT FROM NEW.portal_contact_ids
)
EXECUTE FUNCTION public.helpdock_ticket_portal_push();--> statement-breakpoint

-- A message takes the ticket's facts on the way in, and again if its kind ever
-- changes. Only `public` and `ai` messages reach a customer.
CREATE FUNCTION public.helpdock_ticket_message_portal_scope()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
  NEW.portal_contact_ids := '{}'::uuid[];
  NEW.portal_account_id := NULL;

  IF NEW.kind IN ('public', 'ai') THEN
    SELECT coalesce(t.portal_contact_ids, '{}'::uuid[]),
           CASE WHEN t.portal_eligible AND NOT t.portal_private THEN t.account_id END
    INTO NEW.portal_contact_ids, NEW.portal_account_id
    FROM public.tickets t
    WHERE t.id = NEW.ticket_id
    FOR SHARE OF t;
  END IF;

  RETURN NEW;
END;
$$;--> statement-breakpoint

